-- Movimentar estoque de forma atômica (usado pelo app)
create or replace function movimentar_estoque(
  p_produto_id uuid,
  p_tipo text,
  p_quantidade integer,
  p_motivo text default null,
  p_usuario text default null
) returns integer
language plpgsql as $$
declare
  v_delta integer;
  v_saldo integer;
begin
  if p_tipo = 'entrada' then
    v_delta := abs(p_quantidade);
  elsif p_tipo in ('saida', 'venda') then
    v_delta := -abs(p_quantidade);
  elsif p_tipo = 'ajuste' then
    v_delta := p_quantidade;
  else
    raise exception 'Tipo de movimentação inválido: %', p_tipo;
  end if;

  update produtos
     set quantidade = quantidade + v_delta,
         status = case when p_tipo = 'venda' and quantidade + v_delta = 0 then 'vendido' else status end
   where id = p_produto_id
  returning quantidade into v_saldo;

  if v_saldo is null then
    raise exception 'Produto não encontrado';
  end if;

  insert into movimentacoes (produto_id, tipo, quantidade, saldo_apos, motivo, usuario)
  values (p_produto_id, p_tipo, v_delta, v_saldo, p_motivo, p_usuario);

  return v_saldo;
end $$;

