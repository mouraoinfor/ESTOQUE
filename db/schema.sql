-- Baixa de todos os produtos do orçamento numa transação só (trava o orçamento e os produtos)
create or replace function baixar_orcamento(p_id uuid, p_usuario text) returns integer
language plpgsql as $$
declare
  o      record;
  i      record;
  falta  text;
  n      integer := 0;
begin
  select * into o from orcamentos where id = p_id for update;
  if not found then raise exception 'Orçamento não encontrado'; end if;
  if o.status not in ('rascunho', 'aprovado') then
    raise exception 'Orçamento #% está %: não dá para dar baixa', o.numero, o.status;
  end if;
  if exists (select 1 from orcamento_itens where orcamento_id = p_id and produto_id is not null and quantidade <> trunc(quantidade)) then
    raise exception 'Itens do estoque precisam de quantidade inteira';
  end if;

  perform 1 from produtos where id in (select produto_id from orcamento_itens where orcamento_id = p_id) for update;

  select string_agg(format('#%s %s (pedido %s, em estoque %s)', p.codigo, p.nome, t.q, p.quantidade), '; ' order by p.codigo)
    into falta
    from (select produto_id, sum(quantidade)::int as q from orcamento_itens
           where orcamento_id = p_id and produto_id is not null group by produto_id) t
    join produtos p on p.id = t.produto_id
   where t.q > p.quantidade;
  if falta is not null then raise exception 'Saldo insuficiente: %', falta; end if;

  for i in select produto_id, quantidade from orcamento_itens
            where orcamento_id = p_id and produto_id is not null order by ordem loop
    perform movimentar_estoque(i.produto_id, 'saida', i.quantidade::int, format('Orçamento #%s - %s', o.numero, o.titulo), p_usuario);
    n := n + 1;
  end loop;
  if n = 0 then raise exception 'O orçamento não tem itens do estoque para dar baixa'; end if;

  update orcamentos
     set status = 'baixado', baixado_em = now(), baixado_por = p_usuario, aprovado_em = coalesce(aprovado_em, now())
   where id = p_id;
  return n;
end $$;

-- Estorno: devolve ao estoque o que a baixa tirou e volta o orçamento para "aprovado"
create or replace function estornar_orcamento(p_id uuid, p_usuario text) returns integer
language plpgsql as $$
declare
  o  record;
  i  record;
  n  integer := 0;
begin
  select * into o from orcamentos where id = p_id for update;
  if not found then raise exception 'Orçamento não encontrado'; end if;
  if o.status <> 'baixado' then raise exception 'Orçamento #% não está baixado', o.numero; end if;

  for i in select produto_id, quantidade from orcamento_itens
            where orcamento_id = p_id and produto_id is not null order by ordem loop
    perform movimentar_estoque(i.produto_id, 'entrada', i.quantidade::int, format('Estorno orçamento #%s', o.numero), p_usuario);
    n := n + 1;
  end loop;

  update orcamentos set status = 'aprovado', baixado_em = null, baixado_por = null where id = p_id;
  return n;
end $$;

