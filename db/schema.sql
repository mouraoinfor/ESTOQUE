create extension if not exists "pgcrypto";

-- ---------------------------------------------------------------------
-- Usuários (login do sistema)
-- ---------------------------------------------------------------------
create table if not exists usuarios (
  id          uuid primary key default gen_random_uuid(),
  email       text not null unique,
  nome        text,
  senha_hash  text not null,
  created_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- Produtos (cada linha = um produto em uma condição; ex: mesmo modelo
-- novo e usado ficam em linhas separadas)
-- ---------------------------------------------------------------------
create table if not exists produtos (
  id                    uuid primary key default gen_random_uuid(),
  codigo                integer generated by default as identity unique,

  -- Estoque
  nome                  text not null,
  nome_original         text,
  marca                 text,
  modelo                text,
  categoria             text,
  condicao              text not null default 'novo' check (condicao in ('novo', 'usado', 'recondicionado')),
  quantidade            integer not null default 0 check (quantidade >= 0),
  localizacao           text,
  custo                 double precision,
  para_venda            boolean not null default true,
  canal                 text not null default 'mercado_livre' check (canal in ('mercado_livre', 'olx', 'ambos', 'nenhum')),
  status                text not null default 'a_revisar' check (status in ('somente_estoque', 'a_revisar', 'pronto', 'anunciado', 'vendido')),
  observacoes           text,

  -- Conferência
  quantidade_conferida  integer,
  conferido_em          timestamptz,

  -- Anúncio
  titulo_ml             text,
  titulo_olx            text,
  descricao             text,
  ficha_tecnica         jsonb not null default '{}'::jsonb,
  palavras_chave        text[] not null default '{}',
  categoria_ml          text,
  categoria_olx         text,
  conteudo_embalagem    text,
  garantia              text,
  gtin                  text,
  peso_kg               double precision,
  altura_cm             double precision,
  largura_cm            double precision,
  comprimento_cm        double precision,
  preco_sugerido        double precision,
  preco_min             double precision,
  preco_max             double precision,
  preco_venda           double precision,
  link_anuncio          text,

  -- Pesquisa
  fontes                text[] not null default '{}',
  confianca             text check (confianca in ('alta', 'media', 'baixa')),
  pendencias            text,

  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now()
);

create index if not exists produtos_categoria_idx on produtos (categoria);
create index if not exists produtos_status_idx on produtos (status);

-- ---------------------------------------------------------------------
-- Fotos (guardadas no banco, já redimensionadas pelo navegador)
-- ---------------------------------------------------------------------
create table if not exists fotos (
  id          uuid primary key default gen_random_uuid(),
  produto_id  uuid not null references produtos(id) on delete cascade,
  mime        text not null,
  dados       bytea not null,
  ordem       integer not null default 0,
  created_at  timestamptz not null default now()
);

create index if not exists fotos_produto_idx on fotos (produto_id, ordem);

-- ---------------------------------------------------------------------
-- Movimentações (entrada, saída, venda, ajuste de conferência)
-- ---------------------------------------------------------------------
create table if not exists movimentacoes (
  id           uuid primary key default gen_random_uuid(),
  produto_id   uuid not null references produtos(id) on delete cascade,
  tipo         text not null check (tipo in ('entrada', 'saida', 'venda', 'ajuste')),
  quantidade   integer not null,          -- com sinal: + entrou, - saiu
  saldo_apos   integer,
  motivo       text,
  usuario      text,
  created_at   timestamptz not null default now()
);

create index if not exists movimentacoes_produto_idx on movimentacoes (produto_id, created_at desc);

-- updated_at automático
create or replace function set_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

drop trigger if exists produtos_updated_at on produtos;
create trigger produtos_updated_at before update on produtos
  for each row execute function set_updated_at();

-- Movimentar estoque de forma atômica (usado pelo app)
create or replace function movimentar_estoque(
  p_produto_id uuid,
  p_tipo text,
  p_quantidade integer,
  p_motivo text default null,
  p_usuario text default null
) returns integer
language plpgsql as $$
declare
  v_delta integer;
  v_saldo integer;
begin
  if p_tipo = 'entrada' then
    v_delta := abs(p_quantidade);
  elsif p_tipo in ('saida', 'venda') then
    v_delta := -abs(p_quantidade);
  elsif p_tipo = 'ajuste' then
    v_delta := p_quantidade;
  else
    raise exception 'Tipo de movimentação inválido: %', p_tipo;
  end if;

  update produtos
     set quantidade = quantidade + v_delta,
         status = case when p_tipo = 'venda' and quantidade + v_delta = 0 then 'vendido' else status end
   where id = p_produto_id
  returning quantidade into v_saldo;

  if v_saldo is null then
    raise exception 'Produto não encontrado';
  end if;

  insert into movimentacoes (produto_id, tipo, quantidade, saldo_apos, motivo, usuario)
  values (p_produto_id, p_tipo, v_delta, v_saldo, p_motivo, p_usuario);

  return v_saldo;
end $$;
